"""Writes Modules/DoTInfo/DotPeriods.lua: the seconds between two ticks of every damage-over-time spell of WoW: Forever.

    python tools/make_dot_periods.py [--build 1.60.1.70755]

DoTInfo matches a combat hit to a DoT by the rhythm the DoT should have. Its description rarely states the interval
("causing 40 Fire damage over 12 sec"), so DoTInfo assumed 3 seconds except for a few names. The client's SpellEffect
table gives the real period of every periodic damage effect (EffectAuraPeriod): this lists the class spells whose period
is not 3 seconds, by spell id (names are translated, ids are not). Healing over time is not listed (DoTInfo tracks damage).
"""
import argparse
import collections
import csv
import re
import subprocess
import sys
import time
from pathlib import Path

root = Path(__file__).resolve().parent.parent
CACHE = root / "tools" / "db2-cache"
CLASS_MASK = {1, 2, 4, 8, 16, 64, 128, 256, 1024}
NOT_CLASS_LINE = re.compile(r"^(Pet|Beast Training|Mounts|Companions|Meditation|Racial|Orc Racial|Comprehension|Runes|GENERIC)")


def fetch(table, build):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / f"{table}-{build}.csv"
    if path.exists() and path.stat().st_size > 0:
        return path
    url = f"https://wago.tools/db2/{table}/csv?build={build}"
    for attempt in range(3):
        r = subprocess.run(["curl", "-s", "-f", "-m", "300", "-o", str(path), url])
        if r.returncode == 0 and path.exists() and path.stat().st_size > 0:
            return path
        time.sleep(2 + attempt)
    sys.exit(f"could not fetch {url}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="1.60.1.70755")
    build = ap.parse_args().build

    def rows(table):
        with open(fetch(table, build), encoding="utf-8", newline="") as f:
            return list(csv.DictReader(f))

    names = {r["ID"]: r["Name_lang"] for r in rows("SpellName")}
    lines = {r["ID"]: r for r in rows("SkillLine")}
    class_spells = set()
    for r in rows("SkillLineAbility"):
        line = lines.get(r["SkillLine"])
        if line and line["CategoryID"] in ("7", "9") and not NOT_CLASS_LINE.match(line["DisplayName_lang"]):
            class_spells.add(r["Spell"])
    periods = {}
    for e in rows("SpellEffect"):
        if e["DifficultyID"] != "0" or e["SpellID"] not in class_spells:
            continue
        if e["Effect"] in ("6", "27", "35", "65") and e["EffectAura"] in ("3", "53"):
            period = int(e["EffectAuraPeriod"] or 0)
            if period > 0 and period != 3000:
                periods.setdefault(int(e["SpellID"]), set()).add(period / 1000)
    out = [
        "-- UsefulPlatesAndTooltips module DoTInfo: the seconds between two ticks of the damage-over-time spells of WoW: Forever",
        f"-- whose period is not 3 seconds (build {build}, SpellEffect.EffectAuraPeriod). By spell id; DoTInfo falls back to its",
        "-- name table and then to 3 seconds. Generated by tools/make_dot_periods.py; do not edit by hand.",
        "-- Copyright (c) 2026 Ironship. GPL-3.0-or-later.",
        "",
        "local _, BIT = ...",
        "local ns = BIT.Module(\"DoTInfo\")",
        "",
        "ns.DOT_PERIODS = {",
    ]
    for sid in sorted(periods):
        if len(periods[sid]) != 1:
            continue  # two different periods in one spell: left to the description and the learned ticks
        out.append(f"  [{sid}]={next(iter(periods[sid])):g},  -- {names.get(str(sid), '?')}")
    out += ["}", ""]
    (root / "Modules" / "DoTInfo" / "DotPeriods.lua").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"DotPeriods.lua: {sum(1 for s in periods.values() if len(s) == 1)} spells (build {build})")


if __name__ == "__main__":
    main()
